"""Пожелания (кнопки) и количество дней: распознавание в свободном тексте.
Автор: Лиза"""

from travel.text import low, has

WISHES = ["С детьми", "В дождь", "Активно", "Спокойно", "Гастро", "Музеи", "Бюджетно"]

WISH_WORDS = {
    "С детьми": ["ребен", "малыш", "дет", "дочк", "сын", "коляс", "семь"],
    "В дождь":  ["дожд", "непогод", "ливн", "пасмурн"],
    "Активно":  ["активн", "насыщен", "все успеть", "спорт"],
    "Спокойно": ["спокойн", "неспеш", "расслаб", "тихо", "отдохнуть"],
    "Гастро":   ["ресторан", "гастро", "вкусн", "кухн", "мишлен"],
    "Музеи":    ["музе", "искусств", "картин", "выставк", "истори"],
    "Бюджетно": ["дешев", "недорог", "бюджет", "эконом", "студент"],
}

DAY_WORDS = {
    1: ["1 д", "один д", "одного д"],
    2: ["2 д", "два д", "двух д", "выходн"],
    3: ["3 д", "три д", "трех д"],
}


def find_wishes(text):
    """Какие пожелания упомянуты в тексте."""
    t = low(text)
    return [wish for wish in WISHES if has(t, WISH_WORDS[wish])]


def find_days(text):
    """Сколько дней указано в тексте (0 — не указано)."""
    t = low(text)
    days = 0
    for n, words in DAY_WORDS.items():
        if has(t, words):
            days = n
    return days
