"""Уточняющие вопросы: список (до 5) и выбор следующего по тексту запроса.
Автор: Андрей"""

from travel.text import low, has, all_text
from travel.wishes import find_days

MAX_QUESTIONS = 5

# known — слова, по которым понятно, что ответ уже есть в запросе, и вопрос задавать не нужно
QUESTIONS = [
    {"question": "Сколько людей отправятся в путешествие?", "options": ["Один", "Вдвоём", "С детьми", "Компанией"],
     "known": ["один", "одна", "вдвоем", "муж", "жен", "подруг", "друг", "парн", "девушк", "компани", "ребен", "дет", "малыш", "сын", "доч", "семь"]},
    {"question": "Какой темп вам комфортен?", "options": ["Спокойный", "Средний", "Насыщенный"],
     "known": ["спокойн", "неспеш", "расслаб", "активн", "насыщен", "все успеть", "отдохнуть", "средн"]},
    {"question": "Что интереснее всего?", "options": ["Музеи и история", "Прогулки и парки", "Еда и рестораны", "Природа и море"],
     "known": ["музе", "искусств", "истори", "парк", "гуля", "прогул", "поесть", "ресторан", "кухн", "вкусн", "мор", "пляж", "природ", "океан", "архитект", "аниме", "шопинг"]},
    {"question": "Какой бюджет на день?", "options": ["Экономно", "Средний", "Не важно"],
     "known": ["бюджет", "дешев", "недорог", "эконом", "студент", "дорог", "не важно", "мишлен"]},
    {"question": "Сколько дней в городе?", "options": ["1 день", "2 дня", "3 дня"],
     "known": []},
]


def next_question(state):
    """Следующий вопрос, ответа на который ещё нет. None — вопросов больше нет."""
    if len(state["qa"]) >= MAX_QUESTIONS:
        return None
    t = low(all_text(state))
    asked = [qa["question"] for qa in state["qa"]]
    for q in QUESTIONS:
        if q["question"] in asked or has(t, q["known"]):
            continue
        if q["question"] == "Сколько дней в городе?" and find_days(t):
            continue
        return q
    return None
